// Day offset of 1 Baisakh of each year from the epoch; YEAR_START[LAST_YEAR + 1] is the end.
const YEAR_START = {[FIRST_YEAR]: 0};
for (let y = FIRST_YEAR; y <= LAST_YEAR; y++)
    YEAR_START[y + 1] = YEAR_START[y] + MONTH_LENGTHS[y].reduce((a, b) => a + b, 0);

export function isSupported(year) {
    return Object.prototype.hasOwnProperty.call(MONTH_LENGTHS, year);
}

export function daysInMonth(year, month) {
    return MONTH_LENGTHS[year]?.[month - 1] ?? 0;
}

/** Convert a local JS Date to {year, month, day, weekday}; month is 1-12. Returns null if out of range. */
export function fromGregorian(date) {
    let offset = Math.round(
        (Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - EPOCH_UTC) / DAY_MS);
    if (offset < 0 || offset >= YEAR_START[LAST_YEAR + 1])
        return null;

    let year = FIRST_YEAR;
    while (YEAR_START[year + 1] <= offset)
        year++;
    offset -= YEAR_START[year];

    let month = 1;
    while (offset >= MONTH_LENGTHS[year][month - 1])
        offset -= MONTH_LENGTHS[year][month++ - 1];

    return {year, month, day: offset + 1, weekday: date.getDay()};
}

/** Convert a BS date to a local JS Date (midnight). */
export function toGregorian(year, month, day) {
    let offset = YEAR_START[year];
    for (let m = 1; m < month; m++)
        offset += MONTH_LENGTHS[year][m - 1];
    offset += day - 1;
    const utc = new Date(EPOCH_UTC + offset * DAY_MS);
    return new Date(utc.getUTCFullYear(), utc.getUTCMonth(), utc.getUTCDate());
}

const NE_DIGITS = '०१२३४५६७८९';

export function toNepaliDigits(n) {
    return String(n).replace(/\d/g, d => NE_DIGITS[d]);
}
