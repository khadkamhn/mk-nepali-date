export const FIRST_YEAR = 1975;
export const LAST_YEAR = Math.max(...Object.keys(MONTH_LENGTHS).map(Number));

// 1 Baisakh 1975 BS == 13 April 1918 AD
const EPOCH_UTC = Date.UTC(1918, 3, 13);
const DAY_MS = 86400000;

